#!/usr/bin/env python3
"""Local, dependency-free repository inventory for Java/Spring + Angular projects.

This script does not call external services, modify source files, or execute project code.
It writes compact indexes to docs/audit/generated by default.
"""
from __future__ import annotations

import argparse
import csv
import json
import os
import re
import sys
from collections import Counter, defaultdict
from datetime import datetime
from pathlib import Path
from typing import Iterable

EXCLUDED_DIRS = {
    ".git", "node_modules", "target", "dist", "build", "coverage", ".angular",
    ".gradle", "bin", "obj", ".idea", ".vscode", "__pycache__",
    ".pytest_cache", ".mypy_cache", ".venv", "venv", "vendor", "playwright-report",
    "test-results", "tmp", "temp", "logs", ".next", ".nuxt", ".turbo",
}
SENSITIVE_PARTS = {
    ".env", ".npmrc", ".pypirc", "id_rsa", "id_ed25519", "credentials",
    "secrets.json", "secrets.yml", "secrets.yaml", "service-account.json",
}
SENSITIVE_SUFFIXES = {".pem", ".key", ".p12", ".pfx", ".jks", ".keystore", ".crt"}
TEXT_EXTS = {
    ".java", ".kt", ".kts", ".xml", ".yml", ".yaml", ".properties", ".json",
    ".ts", ".tsx", ".js", ".jsx", ".html", ".scss", ".css", ".sql", ".md",
    ".txt", ".gradle", ".sh", ".ps1", ".conf", ".toml", ".gitignore",
    ".dockerignore", ".tf", ".bat", ".cmd", ".graphql", ".gql", ".proto",
    ".properties", ".lock", ".yml",
}
LOCK_NAMES = {"package-lock.json", "pnpm-lock.yaml", "yarn.lock", "bun.lockb", "bun.lock", "gradle.lockfile"}
MAX_TEXT_FILE_BYTES = 2_000_000

JAVA_PATTERNS = {
    "Spring entry points / layers": re.compile(
        r"@SpringBootApplication|@RestController|@Controller\b|@Service\b|@Repository\b|@Component\b|@Configuration\b|@Bean\b|@EnableFeignClients\b"
    ),
    "HTTP mapping annotations": re.compile(
        r"@(RequestMapping|GetMapping|PostMapping|PutMapping|PatchMapping|DeleteMapping|ExceptionHandler)\b"
    ),
    "HTTP clients / OpenFeign": re.compile(
        r"@FeignClient\b|@EnableFeignClients\b|\bRequestInterceptor\b"
    ),
    "Persistence / transactions": re.compile(
        r"@Entity\b|@Table\b|@Id\b|@EmbeddedId\b|@Document\b|@Repository\b|@Query\b|@Transactional\b|\bJpaRepository\b|\bCrudRepository\b|\bMongoRepository\b|\bReactiveMongoRepository\b|\bEntityManager\b|\bMongoTemplate\b"
    ),
    "Cache / Redis": re.compile(
        r"\b(RedisTemplate|StringRedisTemplate|RedisConnectionFactory)\b|@(Cacheable|CacheEvict|CachePut|EnableCaching)\b"
    ),
    "Messaging / RabbitMQ": re.compile(
        r"@RabbitListener\b|\bRabbitTemplate\b|\bAmqpAdmin\b|@(QueueBinding|Exchange|Queue)\b"
    ),
    "Messaging / Kafka": re.compile(
        r"@KafkaListener\b|\bKafkaTemplate\b|\bConsumerRecord\b|\bProducerRecord\b"
    ),
    "Programmatic initializers / seeders": re.compile(
        r"\bclass\b[^{]*\bimplements\s+[^\{]*\b(ApplicationRunner|CommandLineRunner)\b|^\s*@PostConstruct\b"
    ),
    "Security markers": re.compile(
        r"\bSecurityFilterChain\b|\bauthorizeHttpRequests\b|\brequestMatchers\b|@(EnableMethodSecurity|PreAuthorize|PostAuthorize|Secured)\b|\bPasswordEncoder\b|\bOncePerRequestFilter\b|\bUserDetailsService\b|\bAuthenticationProvider\b|(?<![A-Za-z0-9_])Jwt"
    ),
}
ANGULAR_PATTERNS = {
    "Route configuration clues": re.compile(
        r"provideRouter\s*\(|RouterModule\.forRoot|\bRoutes\b|\bpath\s*:|loadChildren\s*:|loadComponent\s*:|canActivate\s*:|canMatch\s*:"
    ),
    "HTTP/API call clues": re.compile(
        r"\b(?:this\.)?http\.(?:get|post|put|patch|delete|request)\s*(?:<[^>]+>)?\s*\("
    ),
    "Guards / interceptors / state clues": re.compile(
        r"HttpInterceptor|HttpInterceptorFn|CanActivate|CanMatch|CanDeactivate|APP_INITIALIZER|provideHttpClient|withInterceptors|BehaviorSubject|signal\s*\("
    ),
}
TODO_RE = re.compile(r"\b(TODO|FIXME|HACK|XXX|BUG)\b", re.IGNORECASE)
SECRET_RE = re.compile(r"(?i)(password|passwd|secret|client_secret|api[_-]?key|access[_-]?token|private[_-]?key)\s*[:=]\s*\S+")


def is_sensitive(path: Path) -> bool:
    name = path.name.lower()
    if name in SENSITIVE_PARTS or any(name.startswith(part) for part in (".env",)):
        return True
    if path.suffix.lower() in SENSITIVE_SUFFIXES:
        return True
    if path.suffix.lower() not in {".java", ".kt"}:
        if any(part in name for part in ("credential", "secret", "service-account")):
            return True
    return False


def is_text_candidate(path: Path) -> bool:
    if is_sensitive(path) or path.name in LOCK_NAMES:
        return False
    if path.name.lower().endswith(".min.js") or path.name.lower().endswith(".min.css"):
        return False
    return path.suffix.lower() in TEXT_EXTS or path.name in {
        "Dockerfile", "Makefile", "Jenkinsfile", "Procfile", ".gitignore", ".dockerignore",
        "AGENTS.md", "CLAUDE.md", "README", "LICENSE",
    }


def safe_read_text(path: Path) -> str | None:
    try:
        if path.stat().st_size > MAX_TEXT_FILE_BYTES:
            return None
        return path.read_text(encoding="utf-8", errors="replace")
    except (OSError, UnicodeError):
        return None


def rel(path: Path, root: Path) -> str:
    try:
        return path.relative_to(root).as_posix()
    except ValueError:
        return str(path)


def walk_files(root: Path, out_dir: Path, max_files: int) -> tuple[list[Path], bool]:
    all_files: list[Path] = []
    truncated = False
    out_resolved = out_dir.resolve()
    root_resolved = root.resolve()
    for current, dirs, files in os.walk(root, topdown=True, followlinks=False):
        current_path = Path(current)
        current_resolved = current_path.resolve()
        filtered = []
        for d in dirs:
            if d in EXCLUDED_DIRS:
                continue
            if d == "out" and current_resolved == root_resolved:
                continue
            candidate = (current_path / d).resolve()
            try:
                candidate.relative_to(out_resolved)
                continue  # don't rescan generated reports
            except ValueError:
                pass
            if (current_path / d).is_symlink():
                continue
            filtered.append(d)
        dirs[:] = filtered
        for filename in files:
            path = current_path / filename
            if path.is_symlink() or is_sensitive(path):
                continue
            all_files.append(path)
            if len(all_files) >= max_files:
                truncated = True
                return all_files, truncated
    return all_files, truncated


def md_table(headers: list[str], rows: Iterable[Iterable[object]]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join(["---"] * len(headers)) + "|"]
    for row in rows:
        cells = [str(c).replace("|", "\\|").replace("\n", " ") for c in row]
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out)


def collect_markers(files: list[Path], root: Path, patterns: dict[str, re.Pattern[str]], allowed_suffixes: set[str], cap: int = 600):
    results: dict[str, list[tuple[str, int, str]]] = defaultdict(list)
    totals: Counter[str] = Counter()
    for path in files:
        if path.suffix.lower() not in allowed_suffixes or not is_text_candidate(path):
            continue
        text = safe_read_text(path)
        if text is None:
            continue
        for lineno, line in enumerate(text.splitlines(), start=1):
            for label, pattern in patterns.items():
                if pattern.search(line):
                    totals[label] += 1
                    if len(results[label]) < cap:
                        snippet = line.strip()
                        # Avoid writing obvious inline secrets into reports.
                        if SECRET_RE.search(snippet):
                            snippet = "[línea omitida: posible valor sensible]"
                        if len(snippet) > 180:
                            snippet = snippet[:177] + "..."
                        results[label].append((rel(path, root), lineno, snippet))
    return results, totals


def npm_dependency_summary(path: Path, root: Path) -> str:
    data = safe_read_text(path)
    if data is None:
        return ""
    try:
        obj = json.loads(data)
    except json.JSONDecodeError:
        return f"- `{path.name}`: JSON no válido; revisar manualmente."
    prod = obj.get("dependencies") or {}
    dev = obj.get("devDependencies") or {}
    names = sorted(prod.keys())
    shown = ", ".join(f"`{n}`" for n in names[:35]) or "ninguna declarada"
    if len(names) > 35:
        shown += f" y {len(names) - 35} más"
    return f"- `{rel(path, root)}`: paquete `{obj.get('name', '(sin nombre)')}`, {len(prod)} dependencias de runtime y {len(dev)} de desarrollo. Runtime: {shown}."


def main() -> int:
    parser = argparse.ArgumentParser(description="Genera índices locales y compactos de un repositorio Java/Angular.")
    parser.add_argument("--root", default=".", help="Raíz del repositorio (por defecto: directorio actual)")
    parser.add_argument("--out", default="docs/audit/generated", help="Salida relativa a la raíz o ruta absoluta")
    parser.add_argument("--max-files", type=int, default=30000, help="Límite de archivos inventariados; por defecto 30000")
    args = parser.parse_args()

    root = Path(args.root).expanduser().resolve()
    if not root.is_dir():
        print(f"ERROR: no existe el directorio raíz: {root}", file=sys.stderr)
        return 2
    out_dir = Path(args.out).expanduser()
    if not out_dir.is_absolute():
        out_dir = (root / out_dir).resolve()
    out_dir.mkdir(parents=True, exist_ok=True)

    files, truncated = walk_files(root, out_dir, max(1, args.max_files))
    ext_counts = Counter((p.suffix.lower() or "[sin extensión]") for p in files)
    total_bytes = sum(p.stat().st_size for p in files if p.exists())
    text_files = [p for p in files if is_text_candidate(p)]

    inventory_rows = []
    scanned_chars = 0
    scanned_lines = 0
    file_info: dict[Path, tuple[int, int | None]] = {}
    for path in files:
        try:
            size = path.stat().st_size
        except OSError:
            continue
        lines: int | str = "no analizado"
        if is_text_candidate(path):
            content = safe_read_text(path)
            if content is not None:
                chars = len(content)
                count_lines = len(content.splitlines())
                scanned_chars += chars
                scanned_lines += count_lines
                lines = count_lines
                file_info[path] = (count_lines, chars)
        inventory_rows.append((rel(path, root), path.suffix.lower() or "[sin extensión]", size, lines))

    # Main source indexes (annotation/route lines only; no source code dumps).
    java_results, java_totals = collect_markers(files, root, JAVA_PATTERNS, {".java", ".kt"})
    angular_results, angular_totals = collect_markers(files, root, ANGULAR_PATTERNS, {".ts", ".tsx", ".js", ".jsx"})

    todos: list[tuple[str, int, str]] = []
    todo_counts: Counter[str] = Counter()
    config_files: list[str] = []
    test_files: list[str] = []
    build_files: list[str] = []
    migration_files: list[str] = []
    readme_files: list[str] = []
    npm_summaries: list[str] = []

    config_name_re = re.compile(r"(^|/)(application[^/]*\.(yml|yaml|properties)|angular\.json|tsconfig[^/]*\.json|\.github/workflows/[^/]+|docker-compose[^/]*|compose[^/]*\.ya?ml|\.env\.example)$", re.I)
    for path in files:
        r = rel(path, root)
        name = path.name.lower()
        low = r.lower()
        if name in {"pom.xml", "build.gradle", "build.gradle.kts", "settings.gradle", "settings.gradle.kts", "package.json", "angular.json", "dockerfile", "makefile", "jenkinsfile"} or ".github/workflows/" in low:
            build_files.append(r)
        if config_name_re.search(r):
            config_files.append(r)
        if "readme" in name:
            readme_files.append(r)
        if re.search(r"(^|/)(test|tests|__tests__)/|\.(spec|test)\.(ts|tsx|js|jsx)$|\btests?\.java$", low):
            test_files.append(r)
        if (
            "/migration/" in low
            or "/migrations/" in low
            or "/db/migration/" in low
            or re.search(r"\bV\d+__.*\.sql$", path.name, re.I)
            or re.search(r"(initializer|seeder)\.java$", low)
        ):
            migration_files.append(r)
        if path.name == "package.json":
            summary = npm_dependency_summary(path, root)
            if summary:
                npm_summaries.append(summary)
        if is_text_candidate(path):
            text = safe_read_text(path)
            if text is None:
                continue
            for lineno, line in enumerate(text.splitlines(), start=1):
                match = TODO_RE.search(line)
                if match:
                    todo_counts[match.group(1).upper()] += 1
                    if len(todos) < 300:
                        snippet = line.strip()
                        if SECRET_RE.search(snippet):
                            snippet = "[línea omitida: posible valor sensible]"
                        if len(snippet) > 220:
                            snippet = snippet[:217] + "..."
                        todos.append((r, lineno, snippet))

    # Directory summary for a quick map (only first two levels, excludes generated output).
    dir_counts: Counter[str] = Counter()
    for p in files:
        parts = p.relative_to(root).parts
        if len(parts) > 1:
            key = "/".join(parts[: min(2, len(parts) - 1)])
            dir_counts[key] += 1
        else:
            dir_counts["[raíz]"] += 1

    git_branch = "no disponible"
    git_status = "no disponible"
    try:
        import subprocess
        branch = subprocess.run(["git", "-C", str(root), "branch", "--show-current"], capture_output=True, text=True, timeout=3)
        status = subprocess.run(["git", "-C", str(root), "status", "--short"], capture_output=True, text=True, timeout=3)
        if branch.returncode == 0:
            git_branch = branch.stdout.strip() or "(detached HEAD)"
        if status.returncode == 0:
            lines = [line for line in status.stdout.splitlines() if line.strip()]
            git_status = f"{len(lines)} cambio(s) pendiente(s)" if lines else "limpio"
    except (OSError, Exception):
        pass

    generated_at = datetime.now().astimezone().strftime("%Y-%m-%d %H:%M %Z")
    estimated_tokens = scanned_chars // 4  # only a rough size estimate, not a tokenizer result
    summary = [
        "# Auditoría automática del repositorio",
        "",
        f"- Generado: {generated_at}",
        "- Raíz analizada: `.` (se omite la ruta absoluta local para que el informe sea portable).",
        "- Ejecución: local; sin enviar el código a servicios externos; sin ejecutar la aplicación.",
        f"- Archivos inventariados: **{len(files)}**" + (" (se alcanzó el límite configurado; el inventario puede estar incompleto)." if truncated else "."),
        f"- Tamaño total inventariado: **{total_bytes / (1024 * 1024):.2f} MiB**.",
        f"- Archivos de texto candidatos: **{len(text_files)}**.",
        f"- Líneas de texto leídas: **{scanned_lines:,}**; caracteres: **{scanned_chars:,}**.",
        f"- Estimación muy aproximada de tamaño textual: **{estimated_tokens:,} tokens** (caracteres / 4; no equivale al tokenizer de un modelo).",
        f"- Git: rama `{git_branch}`; estado `{git_status}`.",
        "",
        "## Tipos de archivo",
        "",
        md_table(["Extensión", "Cantidad"], sorted(ext_counts.items(), key=lambda x: (-x[1], x[0]))[:35]),
        "",
        "## Directorios / áreas con más archivos",
        "",
        md_table(["Ruta aproximada", "Archivos"], sorted(dir_counts.items(), key=lambda x: (-x[1], x[0]))[:50]),
        "",
        "## Cómo usar este resultado",
        "",
        "1. Lee este resumen primero; no pegues automáticamente todos los archivos en el modelo.",
        "2. Consulta `01-java-index.md` o `02-angular-index.md` para localizar clases, rutas y llamadas relevantes.",
        "3. Consulta `03-config-tests.md` y `04-todos.md` antes de planificar cambios.",
        "4. Para una tarea concreta, pide al agente que lea solo los documentos y archivos del módulo afectado y que verifique las relaciones antes de editar.",
        "5. Los índices son pistas heurísticas, no un análisis semántico completo; valida las rutas y dependencias contra el código.",
    ]

    def marker_report(title: str, result_map, totals: Counter[str]) -> str:
        out = [f"# {title}", "", "Este archivo contiene líneas indicadoras y ubicaciones, no volcados completos de código.", ""]
        if not result_map:
            out.append("No se encontraron coincidencias en las extensiones revisadas.")
        for label, _pattern in (JAVA_PATTERNS.items() if "Java" in title else ANGULAR_PATTERNS.items()):
            out.extend([f"## {label} — {totals[label]} coincidencia(s)", ""])
            entries = result_map.get(label, [])
            if not entries:
                out.append("Sin coincidencias.")
                out.append("")
                continue
            out.extend([md_table(["Archivo", "Línea", "Indicador"], entries), ""])
            if totals[label] > len(entries):
                out.append(f"> Se muestran {len(entries)} de {totals[label]} coincidencias para mantener compacto el informe.")
                out.append("")
        out.extend(["## Advertencia", "", "La búsqueda es textual: puede omitir anotaciones multilínea o producir falsos positivos. Usa los resultados como índice de navegación."])
        return "\n".join(out) + "\n"

    config_lines = ["# Configuración, dependencias y pruebas", "", "## Archivos de construcción / CI", ""]
    config_lines.append("\n".join(f"- `{p}`" for p in sorted(set(build_files))) or "No se detectaron archivos habituales de construcción/CI.")
    config_lines.extend(["", "## Configuración detectada", ""])
    config_lines.append("\n".join(f"- `{p}`" for p in sorted(set(config_files))) or "No se detectaron los nombres de configuración habituales.")
    config_lines.extend(["", "## Manifiestos npm y dependencias de runtime", ""])
    config_lines.extend(npm_summaries or ["No se detectaron `package.json` legibles."])
    config_lines.extend(["", "## Pruebas detectadas (por nombre o carpeta)", ""])
    config_lines.append("\n".join(f"- `{p}`" for p in sorted(set(test_files))[:400]) or "No se detectaron pruebas por los patrones de nombre habituales.")
    if len(set(test_files)) > 400:
        config_lines.append(f"- ... y {len(set(test_files)) - 400} archivos de prueba adicionales (omitidos aquí).")
    config_lines.extend(["", "## Migraciones de base de datos detectadas", ""])
    config_lines.append("\n".join(f"- `{p}`" for p in sorted(set(migration_files))[:300]) or "No se detectaron rutas/nombres de migración habituales.")
    if len(set(migration_files)) > 300:
        config_lines.append(f"- ... y {len(set(migration_files)) - 300} migraciones adicionales (omitidas aquí).")
    config_lines.extend(["", "## README / documentación de entrada", ""])
    config_lines.append("\n".join(f"- `{p}`" for p in sorted(set(readme_files))) or "No se detectó un archivo cuyo nombre contenga README.")
    config_lines.extend(["", "## Advertencias", "", "- No se imprimen contenidos de archivos `.env`, certificados, claves u otros archivos identificados como sensibles.", "- No se leen archivos de lockfile para evitar índices largos y poco útiles.", "- La presencia de un archivo no garantiza que esté actualizado ni que el build funcione."])

    todo_lines = ["# TODOs y marcadores pendientes", "", f"Marcadores encontrados: **{sum(todo_counts.values())}**. Se muestran como máximo 300 líneas.", "", "## Conteo por tipo", ""]
    todo_lines.append(md_table(["Tipo", "Cantidad"], sorted(todo_counts.items())))
    todo_lines.extend(["", "## Ubicaciones", ""])
    todo_lines.append(md_table(["Archivo", "Línea", "Texto"], todos) if todos else "No se detectaron TODO/FIXME/HACK/XXX/BUG en los archivos de texto revisados.")
    todo_lines.extend(["", "## Nota", "", "Estos marcadores pueden estar obsoletos o ser intencionales. No constituyen por sí solos defectos confirmados."])

    out_files = {
        "00-summary.md": "\n".join(summary) + "\n",
        "01-java-index.md": marker_report("Índice Java / Spring", java_results, java_totals),
        "02-angular-index.md": marker_report("Índice Angular / TypeScript", angular_results, angular_totals),
        "03-config-tests.md": "\n".join(config_lines) + "\n",
        "04-todos.md": "\n".join(todo_lines) + "\n",
    }
    for name, body in out_files.items():
        (out_dir / name).write_text(body, encoding="utf-8")
    with (out_dir / "files.csv").open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(["path", "extension", "size_bytes", "line_count_or_status"])
        writer.writerows(inventory_rows)

    print(f"Auditoría terminada. Archivos inventariados: {len(files)}")
    print(f"Informes: {out_dir}")
    print("Empieza leyendo: 00-summary.md, después 01-java-index.md / 02-angular-index.md.")
    if truncated:
        print("ADVERTENCIA: se alcanzó --max-files; prueba con --max-files 60000 si necesitas ampliar el inventario.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
